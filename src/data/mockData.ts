// Helper to generate dynamic showtimes for all media across venues
export const generateShowtimes = (): Showtime[] => {
  const showtimes: Showtime[] = [];
  const dates = ['2026-08-20', '2026-08-21', '2026-08-22', '2026-08-23'];
  const times = ['10:30 AM', '01:45 PM', '05:15 PM', '08:45 PM', '11:15 PM'];

  // Base schedule for top movies in all major venues
  MOCK_MEDIA.forEach((media, mIdx) => {
    MOCK_VENUES.forEach((venue, vIdx) => {
      // Pick 2-3 showtimes per venue for this movie
      const timeSlots = [times[(mIdx + vIdx) % times.length], times[(mIdx + vIdx + 2) % times.length]];
      
      dates.forEach((date) => {
        timeSlots.forEach((time, tIdx) => {
          const format = media.formats[tIdx % media.formats.length] || '2D';
          const language = media.languages.includes('Telugu') ? 'Telugu' : media.languages[0] || 'Telugu';
          
          let vipPrice = 450;
          let primePrice = 300;
          let execPrice = 220;
          let classicPrice = 150;

          if (venue.name.includes('IMAX') || format.includes('IMAX')) {
            vipPrice = 850; primePrice = 650; execPrice = 480; classicPrice = 350;
          } else if (venue.name.includes('AMB') || venue.name.includes('Prasads')) {
            vipPrice = 550; primePrice = 390; execPrice = 295; classicPrice = 200;
          }

          showtimes.push({
            id: `st-${media.id}-${venue.id}-${date}-${tIdx}`,
            mediaId: media.id,
            venueId: venue.id,
            screenName: venue.name.includes('Multiplex') ? `Screen ${tIdx + 1} (4K Laser)` : `Main Audi (Dolby Atmos)`,
            date,
            time,
            format,
            language,
            soundType: venue.soundSystem.includes('Atmos') ? 'Dolby Atmos 128-ch' : 'Dolby 7.1',
            basePrices: {
              vip: vipPrice,
              primePlus: primePrice,
              executive: execPrice,
              classic: classicPrice,
            },
            totalSeats: 160,
            availableSeats: 30 + ((mIdx * 17 + vIdx * 13 + tIdx * 7) % 90),
            fillingFast: (mIdx + vIdx) % 2 === 0,
          });
        });
      });
    });
  });

  return showtimes;
};

